#!/usr/bin/env node
// Android Host startup diagnostic. Checks source invariants in CI; the actual
// Gateway must still be tested on the affected Android device.
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const engine=read('app/src/main/java/com/dshmobile/shell/EngineManager.kt')
const activity=read('app/src/main/java/com/dshmobile/shell/MainActivity.kt')
const state=read('app/src/main/java/com/dshmobile/shell/ShellState.kt')
const mcp=read('app/src/main/java/com/dshmobile/shell/McpConfigManager.kt')
assert.match(state,/private const val NORMAL_MCP_DIAGNOSTIC/)
assert.match(state,/fun normalMcpDiagnosticEnabled\(context: Context\)/)
assert.match(state,/fun setNormalMcpDiagnosticEnabled\(context: Context, enabled: Boolean\): Boolean =/)
assert.match(state,/\.edit\(\)\.putBoolean\(NORMAL_MCP_DIAGNOSTIC, enabled\)\.commit\(\)/)
assert.match(engine,/val noMcpDiagnostic = !safeMode && ShellState\.normalMcpDiagnosticEnabled\(context\)/)
assert.match(engine,/mcpConfigManager\.ensureRuntimePatch\(safeMode \|\| noMcpDiagnostic\)/)
assert.match(engine,/!ShellState\.safeModeEnabled\(context\) && !ShellState\.normalMcpDiagnosticEnabled\(context\)/)
assert.match(mcp,/if \(!safeMode\) \{/)
assert.match(mcp,/"\[\]\\n"/)
assert.match(engine,/private val bootStageFile = File\(context\.filesDir, "engine-boot-stage\.txt"\)/)
assert.match(engine,/recordBootStage\("profile-prepared"\)/)
assert.match(engine,/recordBootStage\("mcp-overlay-ready"\)/)
assert.match(engine,/recordBootStage\("node-spawned"\)/)
assert.match(engine,/recordBootStage\("node-live-http-timeout"\)/)
assert.match(engine,/normalProfileLayerDiagnostics\(\)/)
const info=engine.slice(engine.indexOf('  private fun normalProfileLayerDiagnostics()'),engine.indexOf('  /** Last useful engine diagnostics',engine.indexOf('  private fun normalProfileLayerDiagnostics()')))
for(const key of ['profiles/web/cordis.patch.yml','cordis.patch.yml','official=','additional=','home-global patch'])assert.ok(info.includes(key))
assert.ok(!info.includes('append(manifest.readText())'), 'do not export manifest contents')
assert.ok(!info.includes('append(file.readText())'), 'do not export user configuration or tokens')
const method=activity.slice(activity.indexOf('  private fun switchNormalMcpDiagnostic('),activity.indexOf('  private fun switchRecoverySafeMode('))
assert.match(method,/ShellState\.setNormalMcpDiagnosticEnabled\(this, enabled\)/)
assert.match(method,/ShellState\.setSafeModeEnabled\(this, false\)/)
assert.ok(method.indexOf('setNormalMcpDiagnosticEnabled(this, enabled)')<method.indexOf('engineManager.stopEngine()'))
assert.match(method,/EngineManager\.beginMaintenance\(\)/)
assert.match(method,/EngineManager\.endMaintenance\(\)/)
assert.ok(!method.includes('removePlugin('))
assert.ok(!method.includes('backupAndResetProfilePatch('))
assert.match(activity,/正常模式临时跳过 MCP 并重启/)
assert.match(activity,/正常模式：跳过 Android MCP 进行诊断/)
console.log('[DSH] no-MCP boot diagnostic is reversible, preserved across stop and redacted: OK')
