#!/usr/bin/env node
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const activity=read('app/src/main/java/com/dshmobile/shell/MainActivity.kt')
const shell=read('app/src/main/java/com/dshmobile/shell/ShellState.kt')
const stop=read('app/src/main/java/com/dshmobile/shell/EngineManager.kt')
const button=activity.slice(activity.indexOf('    val safeMode = Button(this).apply {',activity.indexOf('  private fun buildGuideView()')),activity.indexOf('    val resetConfig = Button(this).apply {',activity.indexOf('  private fun buildGuideView()')))
assert.match(button,/switchRecoverySafeMode\(enabled\)/)
assert.ok(!button.includes('runProfileMutation('),'recovery switch cannot depend on successful old Host shutdown')
const method=activity.slice(activity.indexOf('  private fun switchRecoverySafeMode('),activity.indexOf('  private fun runProfileMutation('))
assert.match(method,/profileMutationRunning\.compareAndSet\(false, true\)/)
assert.match(method,/EngineManager\.beginMaintenance\(\)/)
assert.match(method,/EngineManager\.endMaintenance\(\)/)
assert.match(method,/ShellState\.setSafeModeEnabled\(this, enabled\)/)
assert.match(method,/engineManager\.stopEngine\(\)/)
assert.ok(method.indexOf('ShellState.setSafeModeEnabled(this, enabled)')<method.indexOf('engineManager.stopEngine()'),'persist recovery preference before attempting to stop a stuck Host')
assert.match(method,/if \(!stopped\) \{/)
assert.match(method,/return@Thread/)
assert.match(method,/强行停止/)
assert.match(method,/不要清除数据/)
assert.ok(!method.includes('rollbackOnBootFailure'),'do not undo the next-boot choice merely because old Host cannot be stopped')
assert.ok(!method.includes('backupAndResetProfilePatch'),'never reset user settings in recovery mode')
assert.match(shell,/fun setSafeModeEnabled\(context: Context, enabled: Boolean\): Boolean =/)
assert.match(shell,/putBoolean\(SAFE_MODE, enabled\)\.commit\(\)/)
assert.match(stop,/val safeMode = ShellState\.safeModeEnabled\(context\)/)
console.log('[DSH] offline-safe-mode recovery persists next boot even when stopEngine fails')
