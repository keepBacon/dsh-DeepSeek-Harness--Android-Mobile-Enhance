#!/usr/bin/env node
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const source = p => readFileSync(new URL('../'+p, import.meta.url), 'utf8')
const activity = source('app/src/main/java/com/dshmobile/shell/MainActivity.kt')
const state = source('app/src/main/java/com/dshmobile/shell/ShellState.kt')
const provider = source('app/src/main/res/xml/workspace_file_paths.xml')
const span = (a,b) => {
  const first=activity.indexOf(a),last=activity.indexOf(b,first+a.length)
  assert.ok(first>=0&&last>first,'missing Android workspace method: '+a)
  return activity.slice(first,last)
}
const chooser=span('  private fun showWorkspaceFileChooser(','  private fun isExternalFileWorkspace(')
const external=span('  private fun externalFileWorkspaceRoot()','  private fun chooseExternalFileWorkspace(')
const choose=span('  private fun chooseExternalFileWorkspace(','  private fun finishWorkspaceFileChooser(')
const pick=span('  private val externalFileWorkspacePicker =','  private val workspaceFilePicker =')
const open=span('  private fun openWorkspaceFileSelection(','  private fun showWorkspaceFileSelection(')
const hostCwd=span('  private fun rememberActiveWorkspacePath(','  private fun currentWorkspaceRoot(')
assert.ok(chooser.includes('添加文件 · 选择工作区'))
assert.ok(chooser.includes('应用私有存储'))
assert.ok(chooser.includes('用户外部存储'))
assert.ok(chooser.includes('选择外部存储目录…'))
assert.ok(chooser.includes('java.io.File(filesDir, "home")'),
  'private workspace must expose existing DSH HOME rather than an empty new root')
assert.ok(!chooser.includes('currentWorkspaceRoot()'), 'upload chooser must not be hardwired to active Host cwd')
assert.ok(!chooser.includes('ShellState.lastWorkspacePath('), 'upload choices must not be populated from session cwd')
assert.ok(choose.includes('Environment.isExternalStorageManager()'))
assert.ok(choose.includes('requestWorkspaceStorageAccess()'))
assert.ok(choose.includes('externalFileWorkspacePicker.launch(null)'))
assert.ok(choose.includes('finishWorkspaceFileChooser(null)'))
assert.ok(pick.includes('OpenDocumentTree()'))
assert.ok(pick.includes('ShellState.rememberExternalFileChooserDirectory'))
assert.ok(pick.includes('isExternalFileWorkspace(root)'))
assert.ok(!pick.includes('ShellState.rememberWorkspacePath('), 'attachment picker must not rewrite active workspace')
assert.ok(external.includes('ShellState.externalFileChooserDirectory(this)'))
assert.ok(external.includes('isExternalFileWorkspace(it)'))
assert.ok(open.includes('FileProvider.getUriForFile'))
assert.ok(open.includes('isInsideWorkspace(root, canonical)'))
assert.ok(hostCwd.includes('ShellState.rememberWorkspacePath(this, canonical.absolutePath)'),
  'existing DSH session cwd tracking remains independent')
assert.ok(state.includes('private const val LAST_WORKSPACE_PATH ='))
assert.ok(state.includes('private const val EXTERNAL_FILE_CHOOSER_DIR ='))
assert.ok(state.includes('fun externalFileChooserDirectory('))
assert.ok(state.includes('fun rememberExternalFileChooserDirectory('))
assert.ok(provider.includes('<external-path name="external-workspace"'))
assert.ok(provider.includes('<files-path name="private-workspace"'))
console.log('[DSH] dual external/private attachment workspaces and independent Host cwd contracts OK')
