#!/usr/bin/env node
// Official-only diagnostic uses original DSH_HOME but never mutates its Web
// profile. Actual user-device Gateway readiness remains a separate test.
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const engine=read('app/src/main/java/com/dshmobile/shell/EngineManager.kt')
const app=read('app/src/main/java/com/dshmobile/shell/MainActivity.kt')
const state=read('app/src/main/java/com/dshmobile/shell/ShellState.kt')
const start=engine.slice(engine.indexOf('  fun startEngine('),engine.indexOf('  /** Preserve an actionable reason'))
const prep=engine.slice(engine.indexOf('  private fun prepareOfficialOnlyDiagnosticProfile()'),engine.indexOf('  /** Start the dsh web engine'))
assert.match(state,/fun officialOnlyDiagnosticEnabled\(context: Context\)/)
assert.match(state,/fun setOfficialOnlyDiagnosticEnabled\(context: Context, enabled: Boolean\): Boolean =/)
assert.match(state,/putBoolean\(OFFICIAL_ONLY_DIAGNOSTIC, enabled\)\.commit\(\)/)
assert.match(start,/val officialProbe = !safeMode && ShellState\.officialOnlyDiagnosticEnabled\(context\)/)
assert.match(start,/else if \(officialProbe\) prepareOfficialOnlyDiagnosticProfile\(\) else null/)
assert.match(start,/mcpConfigManager\.ensureRuntimePatch\(safeMode \|\| officialProbe \|\| noMcpDiagnostic\)/)
assert.match(start,/engineEnv\(preload, isolatedSafeHome = safeMode\)/)
assert.match(start,/if \(!safeMode && !officialProbe && !skipPrebootCompat\)/)
assert.match(prep,/File\(ensureDshDataHome\(\), "profiles\/\$name"\)/)
assert.match(prep,/android-official-probe-web-20261113/)
assert.match(prep,/marker\.readText\(\)/)
assert.match(prep,/Files\.isSymbolicLink\(marker\.toPath\(\)\)/)
assert.match(prep,/Files\.isSymbolicLink\(File\(dir, filename\)\.toPath\(\)\)/)
assert.match(prep,/JSONArray\(\)\.put\("@deepseek-ai\/dsh-base"\)\.put\("@deepseek-ai\/dsh-web-app"\)/)
for(const path of ['profiles/web','profilePatchFile(','backupAndResetProfilePatch(','installPlugin(','removePlugin(','sessions','attachments','credentials'])
 assert.ok(!prep.includes(path),'diagnostic preparation must not touch the existing '+path)
const operation=app.slice(app.indexOf('  private fun switchOfficialOnlyDiagnostic('),app.indexOf('  private fun switchNormalMcpDiagnostic('))
assert.match(operation,/ShellState\.setOfficialOnlyDiagnosticEnabled\(this, enabled\)/)
assert.match(operation,/ShellState\.setSafeModeEnabled\(this, false\)/)
assert.ok(operation.indexOf('setOfficialOnlyDiagnosticEnabled(this, enabled)')<operation.indexOf('engineManager.stopEngine()'))
assert.match(operation,/EngineManager\.beginMaintenance\(\)/)
assert.match(operation,/EngineManager\.endMaintenance\(\)/)
assert.match(app,/原数据目录仅启动官方组件（诊断）/)
assert.match(app,/guide\.addView\(officialProbe\)/)
console.log('[DSH] real-home official-only diagnostic never edits the normal web profile: OK')
