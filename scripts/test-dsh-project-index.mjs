#!/usr/bin/env node
import assert from 'node:assert/strict'
import {mkdtemp,mkdir,writeFile,rm,symlink,readFile} from 'node:fs/promises'
import {tmpdir} from 'node:os'
import {join} from 'node:path'
const home=await mkdtemp(join(tmpdir(),'dsh-p1-test-'))
process.env.DSH_PROJECT_INDEX_DIR=join(home,'cache')
const {workspaceCall,workspaceTools}=await import('./dsh-project-index.mjs')
const project=join(home,'project')
const write=(file,text)=>writeFile(join(project,file),text)
try{
 await mkdir(join(project,'src'),{recursive:true})
 await mkdir(join(project,'node_modules'))
 await write('node_modules/ignored.ts','export const ignored=1\n')
 await write('src/a.ts',"export function alpha(x: number) { return x + 1 }\n")
 await write('src/b.ts',"import {alpha} from './a';\nexport const beta=alpha(1)\n")
 await write('src/c.ts',"import {beta} from './b';\nconsole.log(beta)\n")
 await write('src/app.py',"from .helpers import helper\nclass Engine:\n def run(self): return helper()\n")
 await write('src/helpers.py',"def helper(): return 3\n")
 await write('src/Utils.kt',"package sample\nclass Utils {\n  fun hello() { }\n}\n")
 await write('src/native.cpp',"#include \"header.h\"\nint make_value() { return 42; }\n")
 await write('src/header.h',"int make_value();\n")
 await write('src/tool.luau',"local function runTask() return 1 end\n")
 await write('src/build.sh',"function compile_project() {\n  echo test\n}\n")
 await symlink(project,join(project,'src','loop'))
 const indexed=await workspaceCall('workspace_index',{root:project})
 assert.equal(indexed.stats.total,10)
 assert.equal(indexed.stats.changed,10)
 assert.ok(indexed.stats.skipped>=1)
 assert.equal(indexed.stats.complete,true)
 const indexedAgain=await workspaceCall('workspace_index',{root:project})
 assert.equal(indexedAgain.stats.reused,10)
 assert.equal(indexedAgain.stats.changed,0)
 const symbols=await workspaceCall('workspace_symbols',{root:project,query:'alpha'})
 assert.ok(symbols.results.some(s=>s.file==='src/a.ts'&&s.name==='alpha'))
 const kotlin=await workspaceCall('workspace_symbols',{root:project,query:'Utils'})
 assert.ok(kotlin.results.some(s=>s.language==='Kotlin'&&s.confidence==='heuristic'))
 const python=await workspaceCall('workspace_symbols',{root:project,query:'helper'})
 assert.ok(python.results.some(s=>s.language==='Python'))
 const cpp=await workspaceCall('workspace_symbols',{root:project,query:'make_value'})
 assert.ok(cpp.results.some(s=>s.language==='C++'))
 const luau=await workspaceCall('workspace_symbols',{root:project,query:'runTask'})
 assert.ok(luau.results.some(s=>s.language==='Luau'))
 const graph=await workspaceCall('workspace_dependencies',{root:project})
 assert.ok(graph.edges.some(x=>x.from==='src/b.ts'&&x.to==='src/a.ts'))
 assert.ok(graph.edges.some(x=>x.from==='src/c.ts'&&x.to==='src/b.ts'))
 assert.ok(graph.edges.some(x=>x.from==='src/app.py'&&x.to==='src/helpers.py'))
 assert.ok(graph.edges.some(x=>x.from==='src/native.cpp'&&x.to==='src/header.h'))
 const impact=await workspaceCall('workspace_impact',{root:project,changedFiles:['src/a.ts']})
 assert.deepEqual(impact.affected.map(x=>x.file).sort(),['src/b.ts','src/c.ts'])
 const candidate=await workspaceCall('workspace_references',{root:project,name:'helper',semantic:false})
 assert.ok(candidate.results.some(x=>x.file==='src/app.py'))
 assert.equal(candidate.precision,'heuristic')
 const definition=await workspaceCall('workspace_definition',{root:project,name:'Utils'})
 assert.ok(definition.results.some(x=>x.file==='src/Utils.kt'))
 await write('src/a.ts',"export function gamma(x: number) { return x + 2 }\n")
 const changed=await workspaceCall('workspace_index',{root:project})
 assert.equal(changed.stats.changed,1)
 assert.equal(changed.stats.reused,9)
 assert.equal((await workspaceCall('workspace_symbols',{root:project,query:'alpha'})).results.length,0)
 assert.ok((await workspaceCall('workspace_symbols',{root:project,query:'gamma'})).results.length)
 await rm(join(project,'src','b.ts'))
 const removed=await workspaceCall('workspace_index',{root:project})
 assert.equal(removed.stats.removed,1)
 const graph2=await workspaceCall('workspace_diagnostics',{root:project})
 assert.ok(graph2.issues.some(x=>x.file==='src/c.ts'&&/Unresolved/.test(x.message)))
 await assert.rejects(workspaceCall('workspace_impact',{root:project,changedFiles:['../outside.ts']}),/escapes/)
 const records=JSON.parse(await readFile(join(process.env.DSH_PROJECT_INDEX_DIR,await (async()=>{
  const {readdir}=await import('node:fs/promises');return (await readdir(process.env.DSH_PROJECT_INDEX_DIR))[0]})()),'utf8'))
 assert.equal(records.version,1)
 assert.equal(records.root,project)
 // A project with >128 TypeScript sources should retain semantic navigation.
 await mkdir(join(project,'large'))
 for(let i=0;i<145;i++)await writeFile(join(project,'large','f'+i+'.ts'),
   i===0?'export function uniqueLongProjectSymbol(){return 7}\n':"export const num"+i+" = "+i+"\n")
 await writeFile(join(project,'large','client.ts'),
   "import {uniqueLongProjectSymbol} from './f0'\nexport const use = uniqueLongProjectSymbol()\n")
 const largeIndex=await workspaceCall('workspace_index',{root:project})
 assert.ok(largeIndex.stats.total>128)
 const semantic=await workspaceCall('workspace_references',{root:project,
   name:'uniqueLongProjectSymbol',file:'large/client.ts',line:2,column:20,limit:50})
 assert.equal(semantic.strategy,'typescript-language-service')
 assert.equal(semantic.precision,'semantic')
 assert.ok(semantic.results.some(x=>x.file==='large/f0.ts'))
 const precise=await workspaceCall('workspace_definition',{root:project,
   name:'uniqueLongProjectSymbol',file:'large/client.ts',line:2,column:20,limit:50})
 assert.equal(precise.precision,'semantic')
 assert.ok(precise.results.some(x=>x.file==='large/f0.ts'))
 assert.equal(workspaceTools.length,8)
 console.log('[DSH] P1 incremental multi-language workspace index, graph and impact: OK')
}finally{await rm(home,{recursive:true,force:true})}
