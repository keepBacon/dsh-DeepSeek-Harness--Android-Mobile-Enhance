#!/usr/bin/env node
// Android Web trial recovery must not reuse a Host started under a different
// profile. Source contracts only; actual readiness requires the user's device.
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read = p => readFileSync(new URL('../' + p, import.meta.url), 'utf8')
const engine = read('app/src/main/java/com/dshmobile/shell/EngineManager.kt')
const app = read('app/src/main/java/com/dshmobile/shell/MainActivity.kt')
const state = read('app/src/main/java/com/dshmobile/shell/ShellState.kt')
const start = engine.slice(engine.indexOf('  fun startEngine('), engine.indexOf('  /** Preserve an actionable reason'))
const attempt = app.slice(app.indexOf('  private fun switchNormalPrebootCompatDiagnostic('), app.indexOf('  private fun switchRecoverySafeMode('))
const flow = app.slice(app.indexOf('  private fun startEngineFlow('), app.indexOf('  /**\n   * Wait for the verified DSH HTTP listener'))
const stop = engine.slice(engine.indexOf('  fun stopEngine('), engine.indexOf('  companion object {', engine.indexOf('  fun stopEngine(')))
assert.match(engine, /private val ACTIVE_PROCESS_MODE = java\.util\.concurrent\.atomic\.AtomicReference<String\?>\(null\)/)
assert.match(engine, /private fun selectedHostMode\(\): String = when/)
assert.match(engine, /fun isManagedHostModeMismatched\(\): Boolean/)
assert.match(engine, /Live managed Host mode: /)
assert.match(engine, /Last Host spawn: /)
assert.match(start, /if \(isManagedHostModeMismatched\(\)\)/)
assert.match(start, /拒绝复用旧 Host/)
assert.match(start, /ACTIVE_PROCESS_MODE\.set\(startedMode\)/)
assert.match(start, /lastLaunchedModeFile\.writeText/)
assert.match(stop, /ACTIVE_PROCESS_MODE\.set\(null\)/)
const fallback = attempt.indexOf('ShellState.recoverFailedPrebootTrial(this, "gateway-unavailable")')
const stopped = attempt.indexOf('if (!engineManager.stopEngine())', fallback)
const restarted = attempt.indexOf('val officialStarted = engineManager.startEngine()', stopped)
assert.ok(fallback > 0 && stopped > fallback && restarted > stopped, 'fallback must persist, stop stale Host and then spawn the official-only Host')
assert.match(attempt.slice(fallback, restarted), /return@Thread/)
assert.match(attempt, /val officialReady = officialStarted && waitForEngineReady\(\)/)
assert.ok(!attempt.includes('removePlugin('))
assert.ok(!attempt.includes('backupAndResetProfilePatch('))
assert.match(flow, /if \(engineManager.isManagedHostModeMismatched\(\)\)/)
assert.ok(flow.indexOf('engineManager.stopEngine()', flow.indexOf('isManagedHostModeMismatched()')) < flow.indexOf('EngineProbe.check(250)'), 'stale Host must stop before HTTP reuse')
assert.match(state, /fun recoverFailedPrebootTrial\(context: Context, reason: String\): Boolean/)
assert.match(state, /saveInterruptedTrialDiagnostics\(context\)/)
console.log('[DSH] recovery kills stale Web Host before starting official-only and preserves trial logs: OK')
